// Puts the idle or muted screen on the 30 second dim countdown. A session
// pauses the timer instead, and error and no-server screens keep full
// brightness for their message, so when this timer fires the state is known to
// be one of these two.
static void restart_dim_timer(void)
{
    lv_timer_set_period(dim_timer, DISPLAY_DIM_AFTER_MILLISECONDS);
    lv_timer_reset(dim_timer);
    lv_timer_resume(dim_timer);
}

void display_cycle_brightness(void)
{
    lvgl_port_lock(0);

    const size_t current_index = brightness_step_index(full_brightness_percent);
    if (current_index == SIZE_MAX) {
        // load_brightness() rejects a stored value that is not a step, and the
        // level only changes here, so an unknown value means a bug in this file.
        abort();
    }
    const uint8_t next = full_brightness_steps[(current_index + 1) % DISPLAY_BRIGHTNESS_STEP_COUNT];
    full_brightness_percent = next;
    panel_full_brightness_command = next * 255 / 100;
    // A press applies the new level at once, even when the screen is dimmed.
    // Making the first press only wake the screen would hide the level the
    // user is trying to see.
    set_brightness(next);
    // Idle and muted are the only states whose countdown runs, so only those
    // restart it; during a session it stays paused and the new level holds
    // until the state change restores it.
    if (current_state == DISPLAY_STATE_IDLE || current_state == DISPLAY_STATE_MUTED) {
        restart_dim_timer();
    }
    ESP_LOGI(TAG, "Full brightness now %d%%", next);

    lvgl_port_unlock();

    // The flash erase can take tens of milliseconds, which would stall the
    // face animation if it ran under the port's lock. The level is already in
    // effect, so a failed write only means the next boot starts at the old one.
    store_brightness(next);
}

static void dim_timer_callback(lv_timer_t *timer)
{
    (void)timer;
    ESP_LOGI(TAG, "Idle for %d s, dimming the display to %d%%",
             DISPLAY_DIM_AFTER_MILLISECONDS / 1000, DISPLAY_BRIGHTNESS_DIM_PERCENT);
    set_brightness(DISPLAY_BRIGHTNESS_DIM_PERCENT);
    lv_timer_pause(timer);
}

// Restarts the blink and variety cycles from a fresh random interval. Called on
// every state change so a session does not inherit a blink that was already
// due, and so an idle screen starts counting again when it comes back.
static void reset_expression_timers(void)
{
    blink_showing = false;
    blink_started_milliseconds = 0;
    variety_showing = false;
    lv_timer_set_period(blink_timer, random_between(DISPLAY_BLINK_MINIMUM_INTERVAL_MILLISECONDS,
                                                    DISPLAY_BLINK_MAXIMUM_INTERVAL_MILLISECONDS));
    lv_timer_reset(blink_timer);
    lv_timer_set_period(variety_timer, random_between(DISPLAY_VARIETY_MINIMUM_INTERVAL_MILLISECONDS,
                                                      DISPLAY_VARIETY_MAXIMUM_INTERVAL_MILLISECONDS));
    lv_timer_reset(variety_timer);
}

static bool blinking_allowed(void)
{
    // Blinking belongs to a resting expression: idle or muted. A variety
    // moment has its own face and motion, and a session has its own expression,
    // so a blink there would fight it.
    return (current_state == DISPLAY_STATE_IDLE || current_state == DISPLAY_STATE_MUTED) && !variety_showing &&
           (current_face == FACE_IDLE_DEFAULT || current_face == FACE_MUTED);
}

static void blink_timer_callback(lv_timer_t *timer)
{
    // In every other state the timer still reschedules itself, so the first
    // blink after returning to idle or muted comes at a fresh random interval.
    if (!blinking_allowed()) {
        blink_showing = false;
        lv_timer_set_period(timer, random_between(DISPLAY_BLINK_MINIMUM_INTERVAL_MILLISECONDS,
                                                  DISPLAY_BLINK_MAXIMUM_INTERVAL_MILLISECONDS));
        return;
    }

    if (blink_showing) {
        blink_showing = false;
        update_face(false);
        lv_timer_set_period(timer, random_between(DISPLAY_BLINK_MINIMUM_INTERVAL_MILLISECONDS,
                                                  DISPLAY_BLINK_MAXIMUM_INTERVAL_MILLISECONDS));
        return;
    }

    blink_showing = true;
    blink_started_milliseconds = lv_tick_get();
    update_face(false);
    // The animation timer interpolates the lid from the start time; this fire
    // only schedules the moment the blink is over.
    lv_timer_set_period(timer, FACE_BLINK_DURATION_MILLISECONDS);
    ESP_LOGD(TAG, "Blink");
}

static void variety_timer_callback(lv_timer_t *timer)
{
    const uint32_t waiting_period =
        random_between(DISPLAY_VARIETY_MINIMUM_INTERVAL_MILLISECONDS, DISPLAY_VARIETY_MAXIMUM_INTERVAL_MILLISECONDS);

    // Only the idle face has spare expressions. In every other state the timer
    // keeps counting down so the next idle period still starts with a fresh
    // interval.
    if (current_state != DISPLAY_STATE_IDLE) {
        variety_showing = false;
        lv_timer_set_period(timer, waiting_period);
        return;
    }

    if (variety_showing) {
        variety_showing = false;
        show_face(FACE_IDLE_DEFAULT);
        lv_timer_set_period(timer, waiting_period);
        ESP_LOGI(TAG, "Variety: back to the idle face");
        return;
    }

    const face_id_t face = (esp_random() & 1) ? FACE_IDLE_CURIOUS : FACE_IDLE_HAPPY_EYES;
    blink_showing = false;
    variety_showing = true;
    show_face(face);
    // The curious face's look cycle is longer than a random duration, so a
    // random one would cut it off before the look to the right. Happy eyes has
    // no motion, so any length suits it.
    const uint32_t showing_period =
        face == FACE_IDLE_CURIOUS ? FACE_CURIOUS_LOOK_PERIOD_MILLISECONDS
                                  : random_between(DISPLAY_VARIETY_MINIMUM_DURATION_MILLISECONDS,
                                                   DISPLAY_VARIETY_MAXIMUM_DURATION_MILLISECONDS);
    lv_timer_set_period(timer, showing_period);
    ESP_LOGI(TAG, "Variety: showing the %s face", face == FACE_IDLE_CURIOUS ? "curious" : "happy eyes");
}

static void drift_timer_callback(lv_timer_t *timer)
{
    // A small step in a random direction each way, clamped to the ±20 px box.
    // Steps rather than a new random offset keep the movement from jumping
    // across the whole box in one go.
    const int16_t step_x = (int16_t)(random_between(0, 2 * DISPLAY_DRIFT_MAXIMUM_STEP_PIXELS)) -
                           DISPLAY_DRIFT_MAXIMUM_STEP_PIXELS;
    const int16_t step_y = (int16_t)(random_between(0, 2 * DISPLAY_DRIFT_MAXIMUM_STEP_PIXELS)) -
                           DISPLAY_DRIFT_MAXIMUM_STEP_PIXELS;
    drift_x = clamp_drift((int16_t)(drift_x + step_x));
    drift_y = clamp_drift((int16_t)(drift_y + step_y));

    // Every shape moves, so the whole face object is repainted; there is no
    // smaller area that covers the move. The conversation screen has a fixed
    // layout, so a step only changes the saved offset there; the next
    // full-size face is drawn at it.
    if (face_has_drift(current_face)) {
        update_face(true);
    }
    ESP_LOGI(TAG, "Drift: (%d, %d) px from home", drift_x, drift_y);

    lv_timer_set_period(timer, random_between(DISPLAY_DRIFT_MINIMUM_INTERVAL_MILLISECONDS,
                                              DISPLAY_DRIFT_MAXIMUM_INTERVAL_MILLISECONDS));
}

