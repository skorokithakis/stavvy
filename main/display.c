static esp_lcd_panel_io_handle_t initialise_panel_io(void)
{
    // A 32-bit command carries the QSPI write opcode in the top byte, followed
    // by the command byte. This is the framing the SH8601 driver expects for
    // both init parameters and pixel writes. One queued transaction is enough
    // because LVGL waits for each partial flush before rendering the next one.
    const esp_lcd_panel_io_spi_config_t io_configuration = {
        .cs_gpio_num = DISPLAY_CHIP_SELECT_PIN,
        .dc_gpio_num = -1,
        .spi_mode = 0,
        .pclk_hz = DISPLAY_SPI_CLOCK_HZ,
        .trans_queue_depth = 1,
        .lcd_cmd_bits = 32,
        .lcd_param_bits = 8,
        .flags.quad_mode = true,
    };
    esp_lcd_panel_io_handle_t io_handle;
    ESP_ERROR_CHECK(
        esp_lcd_new_panel_io_spi((esp_lcd_spi_bus_handle_t)DISPLAY_SPI_HOST, &io_configuration, &io_handle));
    return io_handle;
}

static esp_lcd_panel_handle_t initialise_panel(esp_lcd_panel_io_handle_t io_handle)
{
    const sh8601_vendor_config_t vendor_configuration = {
        .init_cmds = panel_init_commands,
        .init_cmds_size = sizeof(panel_init_commands) / sizeof(panel_init_commands[0]),
        .flags.use_qspi_interface = 1,
    };
    const esp_lcd_panel_dev_config_t panel_configuration = {
        // There is no reset GPIO on this board; the panel is reset in software.
        .reset_gpio_num = GPIO_NUM_NC,
        .rgb_ele_order = LCD_RGB_ELEMENT_ORDER_RGB,
        .bits_per_pixel = 16,
        .vendor_config = (void *)&vendor_configuration,
    };

    esp_lcd_panel_handle_t panel_handle;
    ESP_ERROR_CHECK(esp_lcd_new_panel_sh8601(io_handle, &panel_configuration, &panel_handle));
    ESP_ERROR_CHECK(esp_lcd_panel_reset(panel_handle));
    ESP_ERROR_CHECK(esp_lcd_panel_init(panel_handle));
    return panel_handle;
}

// The CO5300 datasheet frames a register read as DCS 0x03 followed by the
// 24-bit address {0x00, command, 0x00}, and esp_lcd_panel_io_rx_param builds
// exactly that 32-bit word. This is kept as the one attempt at boot: on this
// panel it returns 0xFF, so no display health check can be based on it.
static esp_err_t read_panel_power_mode(uint8_t *power_mode)
{
    const int command = (DISPLAY_QSPI_READ_COMMAND_OPCODE << 24) | (LCD_CMD_RDDPM << 8);
    return esp_lcd_panel_io_rx_param(display_io, command, power_mode, sizeof(*power_mode));
}

static esp_err_t write_panel_brightness(uint8_t percent)
{
    const uint8_t brightness = percent * 255 / 100;
    const int command = (DISPLAY_QSPI_WRITE_COMMAND_OPCODE << 24) | (LCD_CMD_WRDISBV << 8);
    return esp_lcd_panel_io_tx_param(display_io, command, &brightness, sizeof(brightness));
}

// Always writes the command, so the recovery path can use it to restore the
// dim value after re-sending the init list (which sets full brightness).
static void apply_brightness(uint8_t percent)
{
    const esp_err_t result = write_panel_brightness(percent);
    if (result != ESP_OK) {
        ESP_LOGE(TAG, "Setting the panel brightness to %d%% failed (0x%x)", percent, result);
        return;
    }
    brightness_percent = percent;
}

// Skips a panel write when the value is already in effect, so the three state
// changes in a session do not each send a redundant command.
static void set_brightness(uint8_t percent)
{
    if (percent == brightness_percent) {
        return;
    }
    apply_brightness(percent);
}

// Returns the index of one of the steps, or SIZE_MAX when the value is not a
// step. load_brightness() uses the miss to reject a stored value; anywhere else
// a miss means this file passed a value it never produced, so it is a bug.
static size_t brightness_step_index(uint8_t percent)
{
    for (size_t index = 0; index < DISPLAY_BRIGHTNESS_STEP_COUNT; index++) {
        if (full_brightness_steps[index] == percent) {
            return index;
        }
    }
    return SIZE_MAX;
}

// Runs once at boot, before the panel is created, so the init list can bring it
// up at the stored level in one command. nvs_flash_init() has already run in
// main(), so a missing namespace is a first boot rather than an error.
static void load_brightness(void)
{
    nvs_handle_t handle;
    esp_err_t result = nvs_open(DISPLAY_BRIGHTNESS_NVS_NAMESPACE, NVS_READONLY, &handle);
    if (result != ESP_OK) {
        ESP_LOGI(TAG, "No stored brightness, using %d%%", full_brightness_percent);
        return;
    }

    uint8_t stored = 0;
    result = nvs_get_u8(handle, DISPLAY_BRIGHTNESS_NVS_KEY, &stored);
    nvs_close(handle);
    if (result != ESP_OK) {
        ESP_LOGI(TAG, "No stored brightness, using %d%%", full_brightness_percent);
        return;
    }
    const size_t index = brightness_step_index(stored);
    if (index == SIZE_MAX) {
        ESP_LOGW(TAG, "Stored brightness %u%% is not a step, using %d%%", stored, full_brightness_percent);
        return;
    }

    full_brightness_percent = full_brightness_steps[index];
}

static void store_brightness(uint8_t percent)
{
    nvs_handle_t handle;
    ESP_ERROR_CHECK(nvs_open(DISPLAY_BRIGHTNESS_NVS_NAMESPACE, NVS_READWRITE, &handle));
    ESP_ERROR_CHECK(nvs_set_u8(handle, DISPLAY_BRIGHTNESS_NVS_KEY, percent));
    ESP_ERROR_CHECK(nvs_commit(handle));
    nvs_close(handle);
}

void display_request_recovery(void)
{
    // Only a flag: the caller may be the touch task, and the panel bus belongs
    // to the LVGL context.
    atomic_store(&recovery_requested, true);
}

// Called from the LVGL timer, which the port runs with its lock held. Re-sends
// the whole init list because the panel has no reset line, restores the
// brightness and marks every pixel dirty so LVGL flushes the frame again.
static void recover_panel(void)
{
    const uint32_t uptime_seconds = (uint32_t)(esp_timer_get_time() / 1000000);
    ESP_LOGI(TAG, "Touch recovery: re-initialising the panel at %lu s", (unsigned long)uptime_seconds);

    const esp_err_t init_result = esp_lcd_panel_init(display_panel);
    if (init_result != ESP_OK) {
        ESP_LOGE(TAG, "Re-initialising the panel failed (0x%x)", init_result);
        return;
    }
    // The init list resends the brightness command at full brightness, so a
    // dimmed idle screen would come back bright. Restore the value in effect.
    apply_brightness(brightness_percent);

    lv_obj_invalidate(lv_screen_active());
    ESP_LOGI(TAG, "Touch recovery: panel re-initialised at %lu s, screen invalidated",
             (unsigned long)uptime_seconds);
}

static void handle_recovery_request(lv_timer_t *timer)
{
    (void)timer;
    if (!atomic_exchange(&recovery_requested, false)) {
        return;
    }

    const int64_t now = esp_timer_get_time();
    if (last_recovery_microseconds != 0 &&
        now - last_recovery_microseconds < DISPLAY_RECOVERY_MINIMUM_INTERVAL_US) {
        ESP_LOGI(TAG, "Ignoring a touch recovery within 2 s of the previous one");
        return;
    }

    last_recovery_microseconds = now;
    recover_panel();
}

// Runs in the LVGL task. It is the only thing that proves that task is alive,
// because the managed port does not call the watchdog API itself.
static void reset_lvgl_watchdog(lv_timer_t *timer)
{
    (void)timer;
    esp_task_wdt_reset();
}

static uint32_t random_between(uint32_t minimum, uint32_t maximum)
{
    // esp_random() is the hardware RNG; the modulo bias over ranges of a few
    // seconds or pixels is irrelevant here.
    return minimum + esp_random() % (maximum - minimum + 1);
}

static int16_t clamp_drift(int16_t offset)
{
    if (offset > DISPLAY_DRIFT_MAXIMUM_OFFSET_PIXELS) {
        return DISPLAY_DRIFT_MAXIMUM_OFFSET_PIXELS;
    }
    if (offset < -DISPLAY_DRIFT_MAXIMUM_OFFSET_PIXELS) {
        return -DISPLAY_DRIFT_MAXIMUM_OFFSET_PIXELS;
    }
    return offset;
}

static bool shapes_equal(const face_shape_t *first, const face_shape_t *second)
{
    return first->x1 == second->x1 && first->y1 == second->y1 && first->x2 == second->x2 &&
           first->y2 == second->y2 && first->radius == second->radius &&
           first->start_angle == second->start_angle && first->end_angle == second->end_angle &&
           first->kind == second->kind && first->red == second->red && first->green == second->green &&
           first->blue == second->blue && first->opacity == second->opacity &&
           first->stroke_width == second->stroke_width && first->border_sides == second->border_sides;
}

// The area a shape can paint, in the face's coordinates. A line's draw task is
// bounded by the whole stroke width past each end and an arc's by its outer
// radius, so both are matched here rather than tightened to the visible
// pixels: the invalidated area must always contain every pixel that changes.
//
// An arc invalidates its whole circle, not just the visible band. LVGL's
// software arc renderer can spin in draw_buf_flush() when a large arc is
// clipped to a horizontal band (the listening waves, radius about 160 px,
// reproduced a watchdog reset that way), and a circle is the only box that
// always contains the arc and its round caps.
static void shape_area(const face_shape_t *shape, lv_area_t *area)
{
    if (shape->kind == FACE_SHAPE_ARC) {
        const int32_t reach = shape->radius + (shape->stroke_width + 1) / 2;
        area->x1 = shape->x1 - reach;
        area->y1 = shape->y1 - reach;
        area->x2 = shape->x1 + reach;
        area->y2 = shape->y1 + reach;
    } else if (shape->kind == FACE_SHAPE_LINE) {
        const int32_t reach = shape->stroke_width;
        area->x1 = LV_MIN(shape->x1, shape->x2) - reach;
        area->y1 = LV_MIN(shape->y1, shape->y2) - reach;
        area->x2 = LV_MAX(shape->x1, shape->x2) + reach;
        area->y2 = LV_MAX(shape->y1, shape->y2) + reach;
    } else {
        area->x1 = shape->x1;
        area->y1 = shape->y1;
        area->x2 = shape->x2;
        area->y2 = shape->y2;
    }
}

// The conversation screen is a fixed layout with an LVGL label on top of the
// face canvas, so it cannot drift independently of the text. The saved drift
// still belongs to the full-size faces: when a conversation face replaces one,
// the full-object invalidation in show_face() draws the full face at the saved
// offset, and when the conversation face returns it is drawn at zero.
static bool face_has_drift(face_id_t face)
{
    return face != FACE_CONVERSATION_THINKING && face != FACE_CONVERSATION_SPEAKING &&
           face != FACE_CONVERSATION_IDLE;
}

static void draw_shape(lv_layer_t *layer, const face_shape_t *shape)
{
    const lv_color_t colour = lv_color_make(shape->red, shape->green, shape->blue);
    const int16_t offset_x = face_has_drift(current_face) ? drift_x : 0;
    const int16_t offset_y = face_has_drift(current_face) ? drift_y : 0;

    switch (shape->kind) {
    case FACE_SHAPE_FILLED_RECT: {
        lv_draw_rect_dsc_t descriptor;
        lv_draw_rect_dsc_init(&descriptor);
        descriptor.bg_color = colour;
        descriptor.bg_opa = shape->opacity;
        descriptor.radius = shape->radius;
        const lv_area_t area = {
            .x1 = shape->x1 + offset_x,
            .y1 = shape->y1 + offset_y,
            .x2 = shape->x2 + offset_x,
            .y2 = shape->y2 + offset_y,
        };
        lv_draw_rect(layer, &descriptor, &area);
        break;
    }
    case FACE_SHAPE_OUTLINE_RECT: {
        lv_draw_rect_dsc_t descriptor;
        lv_draw_rect_dsc_init(&descriptor);
        descriptor.bg_opa = LV_OPA_TRANSP;
        descriptor.border_color = colour;
        descriptor.border_opa = shape->opacity;
        descriptor.border_width = shape->stroke_width;
        lv_border_side_t border_sides = 0;
        if (shape->border_sides & FACE_BORDER_LEFT) {
            border_sides |= LV_BORDER_SIDE_LEFT;
        }
        if (shape->border_sides & FACE_BORDER_RIGHT) {
            border_sides |= LV_BORDER_SIDE_RIGHT;
        }
        if (shape->border_sides & FACE_BORDER_TOP) {
            border_sides |= LV_BORDER_SIDE_TOP;
        }
        if (shape->border_sides & FACE_BORDER_BOTTOM) {
            border_sides |= LV_BORDER_SIDE_BOTTOM;
        }
        descriptor.border_side = border_sides;
        descriptor.radius = shape->radius;
        const lv_area_t area = {
            .x1 = shape->x1 + offset_x,
            .y1 = shape->y1 + offset_y,
            .x2 = shape->x2 + offset_x,
            .y2 = shape->y2 + offset_y,
        };
        lv_draw_rect(layer, &descriptor, &area);
        break;
    }
    case FACE_SHAPE_ARC: {
        lv_draw_arc_dsc_t descriptor;
        lv_draw_arc_dsc_init(&descriptor);
        descriptor.color = colour;
        descriptor.opa = shape->opacity;
        descriptor.center.x = shape->x1 + offset_x;
        descriptor.center.y = shape->y1 + offset_y;
        // The stored radius is the stroke's centreline; lv_draw_arc takes the
        // outer edge.
        descriptor.radius = (uint16_t)(shape->radius + shape->stroke_width / 2);
        descriptor.width = shape->stroke_width;
        descriptor.start_angle = shape->start_angle;
        descriptor.end_angle = shape->end_angle;
        descriptor.rounded = 1;
        lv_draw_arc(layer, &descriptor);
        break;
    }
    case FACE_SHAPE_LINE: {
        lv_draw_line_dsc_t descriptor;
        lv_draw_line_dsc_init(&descriptor);
        descriptor.p1.x = shape->x1 + offset_x;
        descriptor.p1.y = shape->y1 + offset_y;
        descriptor.p2.x = shape->x2 + offset_x;
        descriptor.p2.y = shape->y2 + offset_y;
        descriptor.color = colour;
        descriptor.opa = shape->opacity;
        descriptor.width = shape->stroke_width;
        descriptor.round_start = 1;
        descriptor.round_end = 1;
        lv_draw_line(layer, &descriptor);
        break;
    }
    }
}

// The face object has no styles of its own; this callback is all that paints
// it. Drift is applied here rather than in faces_build() so the shape list
// stays independent of where the face currently sits.
static void draw_face_event(lv_event_t *event)
{
    lv_layer_t *layer = lv_event_get_layer(event);
    for (int index = 0; index < face_shape_count; index++) {
        draw_shape(layer, &face_shapes[index]);
    }
}

static void log_face_heap(void)
{
    lv_mem_monitor_t monitor;
    lv_mem_monitor(&monitor);
    ESP_LOGI(TAG, "Face with %d shapes: LVGL heap %u bytes free, %u bytes peak used", face_shape_count,
             (unsigned)monitor.free_size, (unsigned)monitor.max_used);
}

// The union of all changed shapes is needed only for faces with arcs: LVGL
// draws the face once per invalidated area and every arc recreates its circle
// masks, which made the renderer spin when the areas were small. The speaking
// and conversation faces contain no arcs, and keeping their changes separate
// stops a moving scrollbar from repainting the mini face (or the reverse).
static bool face_has_arcs(face_id_t face)
{
    switch (face) {
    case FACE_IDLE_DEFAULT:
    case FACE_LISTENING:
    case FACE_MUTED:
    case FACE_IDLE_HAPPY_EYES:
    case FACE_IDLE_CURIOUS:
    case FACE_SURPRISED:
    case FACE_RELIEVED:
        return true;
    case FACE_SPEAKING:
    case FACE_CONVERSATION_THINKING:
    case FACE_CONVERSATION_SPEAKING:
    case FACE_CONVERSATION_IDLE:
    case FACE_COUNT:
        return false;
    }
    return false;
}

// Rebuilds the current face and repaints only what changed. Shapes are
// compared after rounding, so a face that is between two integer frames costs
// nothing to redraw. A new face, a new shape count or a drift step invalidates
// the whole object, because the whole face has moved or been replaced.
static void update_face(bool redraw_everything)
{
    const uint32_t elapsed_ms = lv_tick_elaps(face_shown_milliseconds);
    const face_context_t context = {
        .blink_elapsed_ms = blink_showing ? lv_tick_elaps(blink_started_milliseconds) : 0,
        .bubble_height = conversation_bubble_height,
        .text_height = conversation_text_height,
        .scroll_offset = conversation_scroll_offset,
        .user_bubble_width = conversation_user_bubble_width,
        .user_bubble_height = conversation_user_bubble_height,
    };
    const int new_shape_count = faces_build(current_face, elapsed_ms, &context, next_face_shapes);

    if (redraw_everything || new_shape_count != face_shape_count) {
        lv_obj_invalidate(face_canvas);
    } else {
        const bool merge_changes = face_has_arcs(current_face);
        bool changed_any = false;
        lv_area_t changed;
        for (int index = 0; index < new_shape_count; index++) {
            if (shapes_equal(&face_shapes[index], &next_face_shapes[index])) {
                continue;
            }
            lv_area_t old_area;
            lv_area_t new_area;
            shape_area(&face_shapes[index], &old_area);
            shape_area(&next_face_shapes[index], &new_area);

            const int16_t offset_x = face_has_drift(current_face) ? drift_x : 0;
            const int16_t offset_y = face_has_drift(current_face) ? drift_y : 0;
            const lv_area_t shape_change = {
                .x1 = LV_MIN(old_area.x1, new_area.x1) + offset_x,
                .y1 = LV_MIN(old_area.y1, new_area.y1) + offset_y,
                .x2 = LV_MAX(old_area.x2, new_area.x2) + offset_x,
                .y2 = LV_MAX(old_area.y2, new_area.y2) + offset_y,
            };
            if (!merge_changes) {
                lv_obj_invalidate_area(face_canvas, &shape_change);
            } else if (!changed_any) {
                changed = shape_change;
                changed_any = true;
            } else {
                changed.x1 = LV_MIN(changed.x1, shape_change.x1);
                changed.y1 = LV_MIN(changed.y1, shape_change.y1);
                changed.x2 = LV_MAX(changed.x2, shape_change.x2);
                changed.y2 = LV_MAX(changed.y2, shape_change.y2);
            }
        }

        if (changed_any) {
            lv_obj_invalidate_area(face_canvas, &changed);
        }
    }

    for (int index = 0; index < new_shape_count; index++) {
        face_shapes[index] = next_face_shapes[index];
    }
    face_shape_count = new_shape_count;

    if (!face_heap_logged && elapsed_ms >= 1000) {
        log_face_heap();
        face_heap_logged = true;
    }
}

