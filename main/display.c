// The largest complete UTF-8 prefix no longer than byte_limit. The API text is
// already valid UTF-8, but the prefix search cuts at arbitrary byte positions.
static size_t utf8_prefix_length(const char *text, size_t byte_limit)
{
    size_t length = 0;
    while (length < byte_limit && text[length] != '\0') {
        const unsigned char first = (unsigned char)text[length];
        size_t sequence = 1;
        if ((first & 0xE0) == 0xC0) {
            sequence = 2;
        } else if ((first & 0xF0) == 0xE0) {
            sequence = 3;
        } else if ((first & 0xF8) == 0xF0) {
            sequence = 4;
        }
        if (length + sequence > byte_limit) {
            break;
        }
        size_t index = 1;
        while (index < sequence && text[length + index] != '\0') {
            index++;
        }
        if (index != sequence) {
            break;
        }
        length += sequence;
    }
    return length;
}

// Writes text[0..cut) plus the caller's ellipsis into shown and measures it
// with the label's font and width. shown_size is the destination's capacity.
static bool shown_prefix_fits(const char *text, char *shown, size_t shown_size, size_t cut,
                              const char *ellipsis, const lv_font_t *font, int32_t width, int32_t max_height)
{
    const size_t ellipsis_length = strlen(ellipsis);
    memcpy(shown, text, cut);
    memcpy(shown + cut, ellipsis, ellipsis_length);
    shown[cut + ellipsis_length] = '\0';

    lv_point_t size;
    lv_text_get_size(&size, shown, font, 0, 0, width, LV_TEXT_FLAG_NONE);
    return size.y <= max_height;
}

// Builds the text shown in a static label: the whole string when it fits,
// otherwise the longest UTF-8-safe prefix that still fits with the caller's
// ellipsis appended. The binary search is over byte lengths; each probe
// measures the resulting prefix with the label's own font and width. The last
// space within a small window is preferred as the cut so the ellipsis rarely
// splits a word.
static void build_shown_text(const char *text, char *shown, size_t shown_size, const char *ellipsis,
                             const lv_font_t *font, int32_t width, int32_t max_height)
{
    lv_point_t full_size;
    lv_text_get_size(&full_size, text, font, 0, 0, width, LV_TEXT_FLAG_NONE);
    if (full_size.y <= max_height) {
        strlcpy(shown, text, shown_size);
        return;
    }

    const size_t source_length = strlen(text);
    size_t low = 0;
    size_t high = source_length;
    size_t best_cut = 0;
    while (low < high) {
        const size_t mid = low + (high - low + 1) / 2;
        const size_t cut = utf8_prefix_length(text, mid);
        if (shown_prefix_fits(text, shown, shown_size, cut, ellipsis, font, width, max_height)) {
            best_cut = cut;
            low = mid;
        } else {
            high = mid - 1;
        }
    }

    size_t cut = best_cut;
    for (size_t index = best_cut; index > 0; index--) {
        if (text[index - 1] == ' ') {
            if (best_cut - (index - 1) <= DISPLAY_TRANSCRIPT_SPACE_WINDOW_BYTES) {
                cut = index - 1;
            }
            break;
        }
    }
    while (cut > 0 && text[cut - 1] == ' ') {
        cut--;
    }

    const size_t ellipsis_length = strlen(ellipsis);
    memcpy(shown, text, cut);
    memcpy(shown + cut, ellipsis, ellipsis_length);
    shown[cut + ellipsis_length] = '\0';
}

// C1's transcript is 24 px italic, wraps to at most three lines and ends in an
// ellipsis, with 20x14 padding and a 22 px corner. The bubble width is the
// natural text width plus the padding and border, capped at 340, so a short
// transcript produces a narrow bubble instead of a fixed-width one.
static void configure_transcript_c1(void)
{
    if (transcript_text[0] == '\0') {
        transcript_hide();
        return;
    }

    lv_point_t natural;
    lv_text_get_size(&natural, transcript_text, &dm_sans_italic_24, 0, 0, 10000, LV_TEXT_FLAG_NONE);
    const int32_t horizontal = 2 * (DISPLAY_CONVERSATION_USER_BORDER + DISPLAY_CONVERSATION_C1_USER_PADDING);
    int32_t width = natural.x + horizontal;
    if (width > DISPLAY_CONVERSATION_USER_MAX_WIDTH) {
        width = DISPLAY_CONVERSATION_USER_MAX_WIDTH;
    }
    const int32_t content_width = width - horizontal;

    lv_point_t wrapped;
    lv_text_get_size(&wrapped, transcript_text, &dm_sans_italic_24, 0, 0, content_width, LV_TEXT_FLAG_NONE);
    int32_t lines = (wrapped.y + DISPLAY_CONVERSATION_C1_USER_LINE_HEIGHT - 1) /
                    DISPLAY_CONVERSATION_C1_USER_LINE_HEIGHT;
    if (lines < 1) {
        lines = 1;
    }
    if (lines > DISPLAY_CONVERSATION_C1_USER_MAX_LINES) {
        lines = DISPLAY_CONVERSATION_C1_USER_MAX_LINES;
    }
    const int32_t label_height = lines * DISPLAY_CONVERSATION_C1_USER_LINE_HEIGHT;
    const int32_t vertical = 2 * (DISPLAY_CONVERSATION_USER_BORDER + DISPLAY_CONVERSATION_C1_USER_VERTICAL_PADDING);

    conversation_user_bubble_width = width;
    conversation_user_bubble_height = label_height + vertical;

    build_shown_text(transcript_text, transcript_shown, sizeof(transcript_shown), "\xE2\x80\xA6",
                     &dm_sans_italic_24, content_width, label_height);
    lv_label_set_long_mode(transcript_label, LV_LABEL_LONG_MODE_WRAP);
    lv_obj_set_style_text_font(transcript_label, &dm_sans_italic_24, 0);
    lv_obj_set_pos(transcript_label,
                   DISPLAY_CONVERSATION_USER_RIGHT - width + DISPLAY_CONVERSATION_USER_BORDER +
                       DISPLAY_CONVERSATION_C1_USER_PADDING,
                   DISPLAY_CONVERSATION_USER_TOP + DISPLAY_CONVERSATION_USER_BORDER +
                       DISPLAY_CONVERSATION_C1_USER_VERTICAL_PADDING);
    lv_obj_set_size(transcript_label, content_width, label_height);
    lv_label_set_text_static(transcript_label, transcript_shown);
    lv_obj_clear_flag(transcript_label, LV_OBJ_FLAG_HIDDEN);
}

// C2 and the linger use one 18 px italic line in a 44 px bubble, with 16x8
