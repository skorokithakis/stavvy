// Measures the reply at the label's width and works out the bubble height and
// the scroll range. lv_text_get_size uses the same wrapping and line height as
// the label, so the label, the bubble and the thumb all agree.
static void measure_conversation_text(void)
{
    lv_point_t text_size;
    lv_text_get_size(&text_size, reply_text, &dm_sans_semibold_26, 0, 0,
                     DISPLAY_CONVERSATION_VIEWPORT_WIDTH, LV_TEXT_FLAG_NONE);
    conversation_text_height = text_size.y;

    int32_t bubble_height = conversation_text_height + 52;
    if (bubble_height > DISPLAY_CONVERSATION_BUBBLE_MAX_HEIGHT) {
        bubble_height = DISPLAY_CONVERSATION_BUBBLE_MAX_HEIGHT;
    }
    conversation_bubble_height = bubble_height;

    const int32_t viewport_height = conversation_bubble_height - 12;
    int32_t scroll_distance = conversation_text_height + 40 - viewport_height;
    if (scroll_distance < 0) {
        scroll_distance = 0;
    }
    conversation_scroll_distance = scroll_distance;
    if (conversation_scroll_offset > conversation_scroll_distance) {
        conversation_scroll_offset = conversation_scroll_distance;
    }
}

// Sizes the viewport and the fades from the measured bubble, and puts the label
// at the current scroll offset. The label is taller than the viewport; the
// viewport is its clipping container and the fades sit on top of both edges.
static int32_t conversation_reply_shift(void)
{
    return conversation_user_bubble_height > 0
               ? conversation_user_bubble_height + DISPLAY_CONVERSATION_C2_USER_GAP
               : 0;
}

static void configure_conversation_layout(void)
{
    const int32_t viewport_height = conversation_bubble_height - 12;
    lv_obj_set_pos(conversation_viewport, DISPLAY_CONVERSATION_VIEWPORT_LEFT,
                   DISPLAY_CONVERSATION_VIEWPORT_TOP + conversation_reply_shift());
    lv_obj_set_size(conversation_viewport, DISPLAY_CONVERSATION_VIEWPORT_WIDTH, viewport_height);
    lv_obj_set_pos(conversation_top_fade, 0, 0);
    lv_obj_set_size(conversation_top_fade, DISPLAY_CONVERSATION_VIEWPORT_WIDTH, DISPLAY_CONVERSATION_FADE_HEIGHT);
    lv_obj_set_pos(conversation_bottom_fade, 0, viewport_height - DISPLAY_CONVERSATION_FADE_HEIGHT);
    lv_obj_set_size(conversation_bottom_fade, DISPLAY_CONVERSATION_VIEWPORT_WIDTH,
                    DISPLAY_CONVERSATION_FADE_HEIGHT);
    lv_obj_set_size(conversation_label, DISPLAY_CONVERSATION_VIEWPORT_WIDTH, conversation_text_height);
    lv_obj_set_pos(conversation_label, 0, DISPLAY_CONVERSATION_TEXT_PADDING - conversation_scroll_offset);
    // Apply the new viewport and label geometry before the next draw rather
    // than leaving the label's cached height at its previous value.
    lv_obj_update_layout(conversation_viewport);
}

// The scroll starts after a 1.5 s hold and runs at 16 px/s. Both the label and
// the face's thumb read conversation_scroll_offset, so they cannot drift apart.
// The label move invalidates only the clipped viewport.
static void update_conversation_scroll(void)
{
    if (!conversation_active || conversation_lingering || conversation_scroll_distance <= 0 ||
        current_state != DISPLAY_STATE_SPEAKING) {
        return;
    }

    const uint32_t elapsed_ms = lv_tick_elaps(conversation_started_milliseconds);
    int32_t offset = 0;
    if (elapsed_ms > DISPLAY_CONVERSATION_SCROLL_HOLD_MILLISECONDS) {
        offset = (int32_t)((elapsed_ms - DISPLAY_CONVERSATION_SCROLL_HOLD_MILLISECONDS) *
                           DISPLAY_CONVERSATION_SCROLL_PIXELS_PER_SECOND / 1000);
        if (offset > conversation_scroll_distance) {
            offset = conversation_scroll_distance;
        }
    }
    if (offset == conversation_scroll_offset) {
        return;
    }
    conversation_scroll_offset = offset;
    lv_obj_set_y(conversation_label, DISPLAY_CONVERSATION_TEXT_PADDING - conversation_scroll_offset);
}

static void text_clear_timer_callback(lv_timer_t *timer)
{
    lv_timer_pause(timer);
    if (!conversation_lingering) {
        return;
    }
    conversation_lingering = false;
    conversation_active = false;
    transcript_hide();
    transcript_text[0] = '\0';
    conversation_show(false);
    reply_text[0] = '\0';
    show_face(state_face[current_state]);
}

// The conversation screen and the errors share the reply buffer. The bottom
// line is visible only for an error or a missing server, and the session always
// clears both before reporting "No server", so the generic words are only used
// when the buffer has nothing more specific.
static void show_state_message(display_state_t state)
{
    if (state == DISPLAY_STATE_NO_SERVER) {
        build_shown_text("No server", message_shown, sizeof(message_shown), "...", &lv_font_montserrat_20,
                         DISPLAY_MESSAGE_WIDTH, DISPLAY_MESSAGE_HEIGHT);
        lv_label_set_text_static(message_label, message_shown);
        message_show(true);
    } else if (state == DISPLAY_STATE_ERROR) {
        const char *text = reply_text[0] != '\0' ? reply_text : "Error";
        build_shown_text(text, message_shown, sizeof(message_shown), "...", &lv_font_montserrat_20,
                         DISPLAY_MESSAGE_WIDTH, DISPLAY_MESSAGE_HEIGHT);
        lv_label_set_text_static(message_label, message_shown);
        message_show(true);
    } else {
        message_show(false);
    }
}

static void create_face_screen(void)
{
    lv_obj_t *screen = lv_screen_active();

    // AMOLED pixels that are black are switched off, so a black background is
    // also the lowest-power option for a screen that is idle most of the time.
    lv_obj_set_style_bg_color(screen, lv_color_black(), 0);
    // The screen holds one fixed layout, so it should never scroll; keeping it
    // still also stops a stray swipe from moving the face or the text.
    lv_obj_set_scrollbar_mode(screen, LV_SCROLLBAR_MODE_OFF);
    lv_obj_set_scroll_dir(screen, LV_DIR_NONE);

    // One plain object draws the face from its shape list. It covers the whole
    // screen and sits before the labels, which keeps the text above the face
    // and leaves room for the conversation screen's bubble and small faces.
    // Its own styles are removed: the draw callback is the only thing that
    // paints it, and the black screen shows through everywhere else.
    face_canvas = lv_obj_create(screen);
    lv_obj_remove_style_all(face_canvas);
    lv_obj_set_pos(face_canvas, 0, 0);
    lv_obj_set_size(face_canvas, DISPLAY_WIDTH, DISPLAY_HEIGHT);
    lv_obj_clear_flag(face_canvas, LV_OBJ_FLAG_SCROLLABLE);
    lv_obj_clear_flag(face_canvas, LV_OBJ_FLAG_CLICKABLE);
    lv_obj_add_event_cb(face_canvas, draw_face_event, LV_EVENT_DRAW_MAIN, NULL);

    // The reply is an LVGL label inside a clipping viewport, above the face
    // canvas; the bubble itself is drawn by faces.c underneath. The viewport is
    // hidden until the speaking screen appears, because C1 has no text.
    conversation_viewport = lv_obj_create(screen);
    lv_obj_remove_style_all(conversation_viewport);
    lv_obj_set_pos(conversation_viewport, DISPLAY_CONVERSATION_VIEWPORT_LEFT, DISPLAY_CONVERSATION_VIEWPORT_TOP);
    lv_obj_set_size(conversation_viewport, DISPLAY_CONVERSATION_VIEWPORT_WIDTH,
                    DISPLAY_CONVERSATION_BUBBLE_MAX_HEIGHT - 12);
    lv_obj_clear_flag(conversation_viewport, LV_OBJ_FLAG_SCROLLABLE);
    lv_obj_clear_flag(conversation_viewport, LV_OBJ_FLAG_CLICKABLE);
    lv_obj_add_flag(conversation_viewport, LV_OBJ_FLAG_HIDDEN);

    // The label points at the static reply buffer, so LVGL never copies the
    // reply into its heap. WRAP gives the paragraph the viewport's width.
    conversation_label = lv_label_create(conversation_viewport);
    lv_obj_set_pos(conversation_label, 0, DISPLAY_CONVERSATION_TEXT_PADDING);
    lv_obj_set_size(conversation_label, DISPLAY_CONVERSATION_VIEWPORT_WIDTH, 34);
    lv_label_set_long_mode(conversation_label, LV_LABEL_LONG_MODE_WRAP);
    lv_obj_set_style_text_font(conversation_label, &dm_sans_semibold_26, 0);
    lv_obj_set_style_text_color(conversation_label, lv_color_hex(0xDCDCFF), 0);
    lv_label_set_text_static(conversation_label, reply_text);

    // The fades are children after the label, so they paint over it and stay
    // fixed while it scrolls. A vertical gradient with opaque bubble colour at
    // the outer edge and a transparent stop inward. The gradient is described
    // by the bg_grad_* style properties only: setting a bg_grad descriptor makes
    // LVGL copy its stops instead, which would override them. LVGL's simple
    // vertical gradient path uses the stops' opacity, so this needs no
    // complex-gradient support (which is off in this build).
    conversation_top_fade = lv_obj_create(conversation_viewport);
    lv_obj_remove_style_all(conversation_top_fade);
    lv_obj_clear_flag(conversation_top_fade, LV_OBJ_FLAG_SCROLLABLE);
    lv_obj_clear_flag(conversation_top_fade, LV_OBJ_FLAG_CLICKABLE);
    lv_obj_set_style_bg_opa(conversation_top_fade, LV_OPA_COVER, 0);
    lv_obj_set_style_bg_color(conversation_top_fade, lv_color_hex(0x2A2540), 0);
    lv_obj_set_style_bg_grad_color(conversation_top_fade, lv_color_hex(0x2A2540), 0);
    lv_obj_set_style_bg_main_stop(conversation_top_fade, 0, 0);
    lv_obj_set_style_bg_grad_stop(conversation_top_fade, 255, 0);
    lv_obj_set_style_bg_main_opa(conversation_top_fade, LV_OPA_COVER, 0);
    lv_obj_set_style_bg_grad_opa(conversation_top_fade, LV_OPA_TRANSP, 0);
    lv_obj_set_style_bg_grad_dir(conversation_top_fade, LV_GRAD_DIR_VER, 0);

    conversation_bottom_fade = lv_obj_create(conversation_viewport);
    lv_obj_remove_style_all(conversation_bottom_fade);
    lv_obj_clear_flag(conversation_bottom_fade, LV_OBJ_FLAG_SCROLLABLE);
    lv_obj_clear_flag(conversation_bottom_fade, LV_OBJ_FLAG_CLICKABLE);
    lv_obj_set_style_bg_opa(conversation_bottom_fade, LV_OPA_COVER, 0);
    lv_obj_set_style_bg_color(conversation_bottom_fade, lv_color_hex(0x2A2540), 0);
    lv_obj_set_style_bg_grad_color(conversation_bottom_fade, lv_color_hex(0x2A2540), 0);
    lv_obj_set_style_bg_main_stop(conversation_bottom_fade, 0, 0);
    lv_obj_set_style_bg_grad_stop(conversation_bottom_fade, 255, 0);
    lv_obj_set_style_bg_main_opa(conversation_bottom_fade, LV_OPA_TRANSP, 0);
    lv_obj_set_style_bg_grad_opa(conversation_bottom_fade, LV_OPA_COVER, 0);
    lv_obj_set_style_bg_grad_dir(conversation_bottom_fade, LV_GRAD_DIR_VER, 0);

    // The transcript is an LVGL label on top of the face's outlined user
    // bubble. It points at the static transcript buffer and is hidden until a
    // conversation screen has one. The font and position are set per state.
    transcript_label = lv_label_create(screen);
    lv_obj_set_style_text_font(transcript_label, &dm_sans_italic_24, 0);
    lv_obj_set_style_text_color(transcript_label, lv_color_hex(0x9A98C0), 0);
    lv_obj_set_pos(transcript_label, 0, 0);
    lv_obj_set_size(transcript_label, 0, 0);
    lv_label_set_long_mode(transcript_label, LV_LABEL_LONG_MODE_WRAP);
    lv_label_set_text_static(transcript_label, transcript_shown);
    lv_obj_add_flag(transcript_label, LV_OBJ_FLAG_HIDDEN);

    // The bottom line carries only the error and "No server" messages now. It
    // takes the old transcript and reply space and stays hidden until one of
    // those states needs it.
    message_label = lv_label_create(screen);
    lv_obj_set_style_text_font(message_label, &lv_font_montserrat_20, 0);
    lv_obj_set_style_text_color(message_label, lv_color_hex(0xE0E0E0), 0);
    lv_obj_set_pos(message_label, DISPLAY_MESSAGE_MARGIN, DISPLAY_MESSAGE_TOP);
    lv_obj_set_size(message_label, DISPLAY_MESSAGE_WIDTH, DISPLAY_MESSAGE_HEIGHT);
    lv_label_set_long_mode(message_label, LV_LABEL_LONG_MODE_WRAP);
    lv_label_set_text_static(message_label, message_shown);
    lv_obj_add_flag(message_label, LV_OBJ_FLAG_HIDDEN);

    show_face(state_face[current_state]);
}

void display_init(void)
{
    load_brightness();
    // The init list's 0x51 entry points here, so the panel comes up at the
    // stored level instead of flashing the 60% default before the first
    // brightness command.
    panel_full_brightness_command = full_brightness_percent * 255 / 100;

    initialise_spi_bus();
    display_io = initialise_panel_io();
    display_panel = initialise_panel(display_io);

    // The init list already writes brightness, but sending it here from the
    // configured percentage keeps the value in one place that any recovery
    // path can reuse, at the cost of one extra command at boot.
    apply_brightness(full_brightness_percent);

    // The read returns 0xFF on this panel, which is the idle level of SIO0
    // rather than a power-mode value. It is logged and kept for the heartbeat
    // so the absence of a usable register read is visible in the log, but no
    // health check can be based on it.
    uint8_t power_mode = 0;
    const esp_err_t power_mode_result = read_panel_power_mode(&power_mode);
    if (power_mode_result == ESP_OK) {
        atomic_store(&last_panel_power_mode, power_mode);
        ESP_LOGW(TAG, "Panel power mode at boot: 0x%02X (register reads are not usable on this panel)", power_mode);
    } else {
        ESP_LOGE(TAG, "Could not read the panel power mode at boot (0x%x)", power_mode_result);
    }

    const lvgl_port_cfg_t lvgl_configuration = {
        .task_priority = DISPLAY_LVGL_TASK_PRIORITY,
        .task_stack = DISPLAY_LVGL_TASK_STACK_BYTES,
        .task_affinity = 0,
        .task_max_sleep_ms = 500,
        .task_stack_caps = MALLOC_CAP_INTERNAL | MALLOC_CAP_DEFAULT,
        .timer_period_ms = 5,
    };
    ESP_ERROR_CHECK(lvgl_port_init(&lvgl_configuration));

    const lvgl_port_display_cfg_t display_configuration = {
        .io_handle = display_io,
        .panel_handle = display_panel,
        .buffer_size = DISPLAY_BUFFER_PIXELS,
        .double_buffer = false,
        .hres = DISPLAY_WIDTH,
        .vres = DISPLAY_HEIGHT,
        .monochrome = false,
        .rotation = {
            .swap_xy = false,
            .mirror_x = false,
            .mirror_y = false,
        },
        .rounder_cb = round_area_to_even_coordinates,
        .color_format = LV_COLOR_FORMAT_RGB565,
        .flags = {
            // The panel's QSPI interface expects each 16-bit pixel high byte
            // first, while LVGL stores it in the CPU's little-endian order.
            .buff_dma = true,
            .swap_bytes = true,
        },
    };
    // esp_lvgl_port applies the rotation fields by calling swap_xy even when
    // they are false. The SH8601 driver does not implement swap_xy and logs an
    // error for that call, but it is harmless: this panel runs unrotated.
    ESP_ERROR_CHECK(lvgl_port_add_disp(&display_configuration) != NULL ? ESP_OK : ESP_FAIL);

    // LVGL objects may only be created while the port's lock is held.
    lvgl_port_lock(0);
    create_face_screen();
    lv_timer_create(handle_recovery_request, DISPLAY_RECOVERY_TIMER_PERIOD_MS, NULL);
    lv_timer_create(reset_lvgl_watchdog, DISPLAY_LVGL_WATCHDOG_RESET_MS, NULL);
    lv_timer_create(animation_timer_callback, DISPLAY_ANIMATION_PERIOD_MILLISECONDS, NULL);
    blink_timer = lv_timer_create(blink_timer_callback,
                                  random_between(DISPLAY_BLINK_MINIMUM_INTERVAL_MILLISECONDS,
                                                 DISPLAY_BLINK_MAXIMUM_INTERVAL_MILLISECONDS),
                                  NULL);
    variety_timer = lv_timer_create(variety_timer_callback,
                                    random_between(DISPLAY_VARIETY_MINIMUM_INTERVAL_MILLISECONDS,
                                                   DISPLAY_VARIETY_MAXIMUM_INTERVAL_MILLISECONDS),
                                    NULL);
    drift_timer = lv_timer_create(drift_timer_callback,
                                  random_between(DISPLAY_DRIFT_MINIMUM_INTERVAL_MILLISECONDS,
                                                 DISPLAY_DRIFT_MAXIMUM_INTERVAL_MILLISECONDS),
                                  NULL);
    dim_timer = lv_timer_create(dim_timer_callback, DISPLAY_DIM_AFTER_MILLISECONDS, NULL);
    text_clear_timer = lv_timer_create(text_clear_timer_callback, DISPLAY_TEXT_CLEAR_AFTER_MILLISECONDS, NULL);
    lv_timer_pause(text_clear_timer);
    // The board boots into the idle screen, so its dim countdown starts now.
    restart_dim_timer();
    lv_mem_monitor_t lvgl_memory;
    lv_mem_monitor(&lvgl_memory);
    lvgl_port_unlock();

    // Subscribe the port's task now that the timer that feeds the watchdog
    // exists. The port does not expose its handle, but the task name is fixed
    // by the managed component.
    TaskHandle_t lvgl_task = xTaskGetHandle(DISPLAY_LVGL_TASK_NAME);
    ESP_ERROR_CHECK(lvgl_task != NULL ? ESP_OK : ESP_FAIL);
    ESP_ERROR_CHECK(esp_task_wdt_add(lvgl_task));

    ESP_LOGI(TAG, "CO5300 panel ready, %d x %d, brightness %d%%, LVGL heap %d KB",
             DISPLAY_WIDTH, DISPLAY_HEIGHT, full_brightness_percent, CONFIG_LV_MEM_SIZE_KILOBYTES);
    ESP_LOGI(TAG, "LVGL heap after creating the screen: %u of %u bytes used, %u bytes free",
             (unsigned)(lvgl_memory.total_size - lvgl_memory.free_size),
             (unsigned)lvgl_memory.total_size, (unsigned)lvgl_memory.free_size);
    ESP_LOGI(TAG, "Free heap after display init: %u bytes, minimum free heap: %u bytes, largest free block: %u bytes",
             (unsigned)esp_get_free_heap_size(), (unsigned)esp_get_minimum_free_heap_size(),
             (unsigned)heap_caps_get_largest_free_block(MALLOC_CAP_DEFAULT));
}

int display_last_power_mode(void)
{
    return atomic_load(&last_panel_power_mode);
}

void display_set_transcript(const char *text)
{
    lvgl_port_lock(0);

    strlcpy(transcript_text, text, sizeof(transcript_text));

    if (current_state == DISPLAY_STATE_THINKING) {
        configure_transcript_c1();
        // The user bubble's appearance moves the dots bubble by several
        // shapes, so update_face will take the whole-object invalidation.
        update_face(false);
    } else if (conversation_lingering || (current_state == DISPLAY_STATE_SPEAKING && conversation_active)) {
        configure_transcript_c2();
        measure_conversation_text();
        configure_conversation_layout();
        update_face(true);
    } else {
        // The full-size layouts never show the transcript; it is only stored
        // for a later conversation state.
        transcript_hide();
    }

    lvgl_port_unlock();
}

void display_set_state(display_state_t state)
{
    lvgl_port_lock(0);

    // Repeating the current state is normal during a session (two events may
    // both report "thinking"), and restarting the blink, variety and dim
    // cycles for it would keep them from ever firing.
    if (state != current_state) {
        ESP_LOGI(TAG, "Display state: %s -> %s", state_name[current_state], state_name[state]);
        const display_state_t previous_state = current_state;
        current_state = state;

        // Every state starts at full brightness so a session or a message is
        // readable. Only the idle and muted screens then run the dim countdown;
        // the others pause it, so an idle screen cannot dim under a session or
        // an error message.
        set_brightness(full_brightness_percent);
        if (state == DISPLAY_STATE_IDLE || state == DISPLAY_STATE_MUTED) {
            restart_dim_timer();
        } else {
            lv_timer_pause(dim_timer);
        }

        reset_expression_timers();
        // The linger re-enables it below; every other transition stops it.
        lv_timer_pause(text_clear_timer);

        switch (state) {
        case DISPLAY_STATE_THINKING:
            conversation_active = false;
            conversation_lingering = false;
            conversation_show(false);
            configure_transcript_c1();
            show_face(FACE_CONVERSATION_THINKING);
            break;

        case DISPLAY_STATE_SPEAKING:
            if (reply_text[0] != '\0') {
                conversation_active = true;
                conversation_lingering = false;
                conversation_scroll_offset = 0;
                conversation_started_milliseconds = lv_tick_get();
                configure_transcript_c2();
                measure_conversation_text();
                lv_label_set_text_static(conversation_label, reply_text);
                configure_conversation_layout();
                conversation_show(true);
                show_face(FACE_CONVERSATION_SPEAKING);
            } else {
                // Shortcuts and error sounds have no text, so they keep the
                // full-size speaking face rather than an empty bubble. The
                // full-size layouts never show the transcript.
                conversation_active = false;
                conversation_lingering = false;
                transcript_hide();
                conversation_show(false);
                show_face(FACE_SPEAKING);
            }
            break;

        case DISPLAY_STATE_IDLE:
        case DISPLAY_STATE_MUTED:
            if (previous_state == DISPLAY_STATE_SPEAKING && reply_text[0] != '\0' && conversation_active) {
                // Keep the bubble, the text and the scroll position; only the
                // mini speaking face becomes the mini idle face. Reapply the
                // transcript's C2 size and the reply shift in case the text
                // arrived at a different time. The existing 2.5 s timer ends
                // the linger and restores the full face.
                conversation_lingering = true;
                configure_transcript_c2();
                configure_conversation_layout();
                show_face(FACE_CONVERSATION_IDLE);
                lv_timer_reset(text_clear_timer);
                lv_timer_resume(text_clear_timer);
            } else {
                conversation_active = false;
                conversation_lingering = false;
                transcript_hide();
                conversation_show(false);
                reply_text[0] = '\0';
                show_face(state_face[state]);
            }
            break;

        case DISPLAY_STATE_ERROR:
        case DISPLAY_STATE_NO_SERVER:
            // Errors switch to the full layout immediately; the message is
            // applied below, after the state has been updated.
            conversation_active = false;
            conversation_lingering = false;
            transcript_hide();
            conversation_show(false);
            show_face(FACE_IDLE_DEFAULT);
            break;

        case DISPLAY_STATE_LISTENING:
            conversation_active = false;
            conversation_lingering = false;
            transcript_hide();
            conversation_show(false);
            show_face(FACE_LISTENING);
            break;
        }
    }

    // The message is applied even when the state did not change. The session
    // clears the reply text before reporting "No server", so a second trigger
    // with no server would otherwise leave the idle face without its message:
    // the clear happens, then the state comparison above skips the redraw.
    show_state_message(state);

    lvgl_port_unlock();
}

void display_set_reply(const char *text)
{
    lvgl_port_lock(0);

    strlcpy(reply_text, text, sizeof(reply_text));

    if (current_state == DISPLAY_STATE_ERROR || current_state == DISPLAY_STATE_NO_SERVER) {
        show_state_message(current_state);
        lvgl_port_unlock();
        return;
    }

    if (reply_text[0] == '\0') {
        // An emptied reply during speaking has no bubble to show; the full
        // speaking face is the fallback. While thinking the text is simply
        // stored, and the C1 dots stay up.
        if (current_state == DISPLAY_STATE_SPEAKING && conversation_active) {
            conversation_active = false;
            conversation_lingering = false;
            conversation_show(false);
            show_face(FACE_SPEAKING);
        }
        lvgl_port_unlock();
        return;
    }

    if (conversation_active) {
        // Normally the text arrives at TTS_START while thinking, before the
        // speaking state is set. A replacement or late text is kept in step.
        measure_conversation_text();
        lv_label_set_text_static(conversation_label, reply_text);
        configure_conversation_layout();
        if (current_state == DISPLAY_STATE_SPEAKING) {
            conversation_scroll_offset = 0;
            conversation_started_milliseconds = lv_tick_get();
            lv_obj_set_y(conversation_label, DISPLAY_CONVERSATION_TEXT_PADDING);
        }
    }

    lvgl_port_unlock();
}

void display_clear(void)
{
    display_set_transcript("");
    display_set_reply("");
    display_set_state(DISPLAY_STATE_IDLE);
}
